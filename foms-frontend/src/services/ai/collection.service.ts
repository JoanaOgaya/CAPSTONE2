/**
 * src/services/ai/collection.service.ts
 * Service for Collection Forecasting and Priorities (FR-014..FR-017).
 * All priority rankings, risk scores, and recommendations are computed by the backend.
 */

import { http } from '../apiClient';
import type {
  CollectionPriorityItem,
  FollowUpSuggestion,
  DashboardAiAlert,
} from '../../types/ai';

export interface PriorityQuery {
  page?: number;
  pageSize?: number;
  search?: string;
  sortBy?: string;
  sortDir?: 'asc' | 'desc';
  status?: string;
  scope?: string;
}

export const collectionService = {
  /**
   * Fetches prioritized receivables sorted by server-calculated risk and priority.
   */
  async getPriorityList(query: PriorityQuery = {}): Promise<{ items: CollectionPriorityItem[]; total: number }> {
    const params: Record<string, unknown> = { ...query };
    const res = await http.get<any>('/ai/collection/priorities', params);
    if (Array.isArray(res)) {
      return { items: res, total: res.length };
    }
    return {
      items: Array.isArray(res?.items) ? res.items : [],
      total: typeof res?.total === 'number' ? res.total : (res?.items?.length || 0),
    };
  },

  /**
   * Fetches client follow-up suggestions generated by AI.
   */
  async getSuggestions(clientId?: string): Promise<FollowUpSuggestion[]> {
    const params = clientId ? { clientId } : undefined;
    return http.get<FollowUpSuggestion[]>('/ai/collection/suggestions', params);
  },

  /**
   * Fetches dashboard AI alerts scoped to the current user's role.
   */
  async getDashboardAlerts(scope?: string): Promise<DashboardAiAlert[]> {
    const params = scope ? { scope } : undefined;
    return http.get<DashboardAiAlert[]>('/ai/dashboard/alerts', params);
  },

  /**
   * Logs a human review decision on an AI priority recommendation.
   * Does NOT auto-update official invoice records.
   */
  async logDecision(
    id: string,
    payload: { decision: string; actionTaken: string; remarks?: string; recommendedAction?: string }
  ): Promise<{ success: boolean; message?: string }> {
    return http.post<{ success: boolean; message?: string }>(`/ai/collection/recommendations/${id}/review`, payload);
  },
};
